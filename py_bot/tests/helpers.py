class TempPaths:
    """Подменяет пути config на временную папку (и возвращает обратно)."""

    NAMES = ("SESSION_DIR", "DATA_DIR", "SCORES_DB", "GAME_RECORDS",
             "GAME_LOG", "BOT_LOG")

    def __enter__(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.saved = {n: getattr(config, n) for n in self.NAMES}
        config.SESSION_DIR = root / "sessions"
        config.DATA_DIR = root / "data"
        config.SCORES_DB = root / "data" / "scores.csv"
        config.GAME_RECORDS = root / "records.csv"
        config.GAME_LOG = root / "game.log"
        config.BOT_LOG = root / "bot_flight.log"
        self.root = root
        return self

    def __exit__(self, *exc):
        for n, v in self.saved.items():
            setattr(config, n, v)
        self.tmp.cleanup()
